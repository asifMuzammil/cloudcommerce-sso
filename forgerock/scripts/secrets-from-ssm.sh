#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Rebuild forgerock/.env and medusa/.env from SSM Parameter Store (SecureString),
# using the EC2 instance role - no access keys on the box.
# Also enables the CloudWatch overlay via COMPOSE_FILE.
# Then: docker compose up -d
# ---------------------------------------------------------------------------
set -euo pipefail
cd "$(dirname "$0")/../.."

PREFIX=${SSM_PREFIX:-/cloudcommerce/forgerock}
REGION=${AWS_REGION:-us-east-1}

PARAMS=$(aws ssm get-parameters-by-path --region "$REGION" --path "$PREFIX" \
  --with-decryption --query 'Parameters[].[Name,Value]' --output json)
[ "$(echo "$PARAMS" | jq length)" -gt 0 ] || { echo "No parameters under $PREFIX"; exit 1; }

get() { echo "$PARAMS" | jq -r --arg n "$PREFIX/$1" '.[] | select(.[0]==$n) | .[1]'; }

umask 077
{
  echo "# Generated by scripts/secrets-from-ssm.sh from SSM $PREFIX - DO NOT COMMIT"
  for k in AM_PASSWORDS_AMADMIN_CLEAR AM_ENCRYPTION_KEY AM_AUTHENTICATION_SHARED_SECRET AM_OIDC_CLIENT_SUBJECT_IDENTIFIER_HASH_SALT; do
    echo "$k=$(get "$k")"
  done
  echo "AWS_REGION=$REGION"
  echo "COMPOSE_FILE=docker-compose.yml:docker-compose.aws.yml"
} > forgerock/.env

mkdir -p medusa
echo "FORGEROCK_CLIENT_SECRET=$(get FORGEROCK_CLIENT_SECRET)" > medusa/.env

echo "Wrote forgerock/.env and medusa/.env (mode 600) from $PREFIX"
